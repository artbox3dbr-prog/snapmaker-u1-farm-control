// Runs the real main.js against mock Snapmaker U1 printers (no hardware, no Electron).
//   npm test                 → scripted checks of every bulk operation
//   npm run test:ui          → serves the real UI at http://127.0.0.1:18080/renderer/index.html (SCALE=50 for 50 printers)
'use strict';
const path = require('path'), fs = require('fs'), http = require('http');
const REPO = path.resolve(__dirname, '..');
const mode = process.argv[2] || 'api';
const E = require('electron').__test;
const mock = require('./mock-moonraker.js');

const BASE = 17101;
const SCALE = Number(process.env.SCALE || 0);
const printers = SCALE ? mock.start(BASE, Array.from({ length: SCALE }, (_, k) => (k % 3 === 0 ? { state: 'printing', filename: `peca_${k}.gcode`, progress: (k % 10) / 10 } : { state: 'standby' }))) : mock.start(BASE, [
  { state: 'standby' },
  { state: 'standby', types: ['PLA', 'PLA', 'PLA', 'PLA'] },
  { state: 'printing', filename: 'running.gcode', progress: 0.4 },
  { state: 'standby', exist: [true, true, false, true] },
  { state: 'complete', filename: 'old.gcode', progress: 1 },
]);
// printer 6 (offline): port with nothing listening
const cfg = {
  printers: [
    ...printers.map((p, k) => ({ id: 'p' + k, name: `U1 - ${String(k + 1).padStart(2, '0')}`, host: `127.0.0.1:${p.port}`, group: SCALE ? 'Prateleira ' + 'ABCDE'[Math.floor(k / 10)] : (k < 3 ? 'Prateleira A' : 'Prateleira B') })),
    ...(SCALE ? [] : [{ id: 'p5', name: 'U1 - 06', host: '127.0.0.1:17199', group: 'Prateleira B' }]),
  ],
  language: 'pt', stagger: 1, notifications: true,
};
fs.writeFileSync(path.join(E.userData, 'config.json'), JSON.stringify(cfg));

// sample Snapmaker Orca-style G-code: uses T0 (PLA) and T2 (PETG)
const gfile = path.join(E.userData, 'suporte_rolo.gcode');
{
  const head = '; HEADER_BLOCK_START\n; generated by Snapmaker Orca 2.1.0\n; estimated printing time (normal mode) = 1h 2m 3s\n; filament used [mm] = 1200.00,0.00,300.00,0.00\n; total filament weight [g] = 42.5\n; HEADER_BLOCK_END\n';
  const body = 'G1 X10 Y10 E0.1\n'.repeat(200000); // ~3 MB
  const foot = '; CONFIG_BLOCK_START\n; filament_type = PLA;PLA;PETG;PLA\n; filament_colour = #000000;#FFFFFF;#FF0000;#00FF00\n; CONFIG_BLOCK_END\n';
  fs.writeFileSync(gfile, head + 'T0\n' + body + 'T2\n' + foot);
}
E.dialogState.files = [gfile];

require(path.join(REPO, 'main.js'));
const H = E.handlers;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const jobs = {};
E.hub.on('send', (ch, d) => { if (ch === 'bulk:job') jobs[d.id] = JSON.parse(JSON.stringify(d)); });
async function waitJob(id, ms = 30000) {
  const t0 = Date.now();
  while (!(jobs[id] && jobs[id].done)) { if (Date.now() - t0 > ms) throw new Error('job timeout ' + id); await sleep(100); }
  return jobs[id];
}
const fmt = (j) => Object.entries(j.items).map(([id, x]) => `   ${id} ${x.status.padEnd(7)} ${x.msg}`).join('\n');
let fails = 0;
const check = (cond, msg) => { console.log((cond ? '  ✔ ' : '  ✘ ') + msg); if (!cond) fails++; };

async function api() {
  await sleep(2500); // primeiro ciclo de polling
  const ids = cfg.printers.map((p) => p.id);

  console.log('\n[1] Escolher arquivo + leitura do G-code');
  const files = await H['bulk:pickFiles']();
  console.log('   info:', JSON.stringify(files[0].info));
  check(JSON.stringify(files[0].info.used) === '[0,2]', 'detecta cabeças usadas T0 e T2');
  check(files[0].info.types[2] === 'PETG', 'detecta PETG na T2');
  check(files[0].info.estimatedTime === 3723, 'tempo estimado 1h02m03s');

  console.log('\n[2] Enviar e imprimir em massa (escalonado 1 s, checagem de filamento)');
  let j = await H['bulk:run']({}, { op: 'send', ids, params: { files, start: true, stagger: 1, checkFilament: true } });
  j = await waitJob(j.id);
  console.log(fmt(j));
  check(j.items.p0.status === 'ok', 'U1-01 (filamento certo) imprimindo');
  check(j.items.p1.status === 'error' && /PETG/.test(j.items.p1.msg), 'U1-02 recusada: T2 com PLA em vez de PETG');
  check(j.items.p2.status === 'skipped', 'U1-03 pulada: já está imprimindo');
  check(j.items.p3.status === 'error' && /T2/.test(j.items.p3.msg), 'U1-04 recusada: T2 sem filamento');
  check(j.items.p4.status === 'ok', 'U1-05 (estava concluída) imprimindo');
  check(j.items.p5.status === 'skipped', 'U1-06 offline pulada');
  check(printers[1].files['suporte_rolo.gcode'] && printers[3].files['suporte_rolo.gcode'], 'arquivo chegou mesmo nas que não iniciaram');
  check(printers[0].files['suporte_rolo.gcode'].size === fs.statSync(gfile).size, 'arquivo íntegro (mesmo tamanho)');
  const t0 = Number(printers[0].log.find((l) => l.startsWith('START')).split('@')[1]);
  const t4 = Number(printers[4].log.find((l) => l.startsWith('START')).split('@')[1]);
  check(Math.abs(t4 - t0) >= 950, `inícios escalonados (${t4 - t0} ms entre U1-01 e U1-05)`);
  check(E.notifications.some((n) => /Enviar arquivo/.test(n.title)), 'notificação ao terminar');

  console.log('\n[3] Retirar filamento em massa (todas as cabeças carregadas)');
  await sleep(2200);
  j = await H['bulk:run']({}, { op: 'unload', ids, params: { heads: 'loaded', parallel: 10 } });
  j = await waitJob(j.id);
  console.log(fmt(j));
  check(j.items.p1.status === 'ok' && printers[1].ptc.filament_exist.every((x) => !x), 'U1-02: 4 cabeças retiradas');
  check(printers[1].log.some((l) => l.startsWith('G28')), 'faz home antes (não estava homed)');
  check(j.items.p3.status === 'ok' && /T0, T1, T3/.test(j.items.p3.msg), 'U1-04: só T0, T1, T3 (T2 já vazia)');
  check(j.items.p0.status === 'skipped', 'U1-01 imprimindo: pulada');

  console.log('\n[4] Editar filamento em massa (T0 e T2)');
  const heads = { 0: { type: 'PETG', subtype: 'Basic', vendor: 'Polymaker', color: 'FF7A18FF' }, 2: { type: 'PLA', subtype: 'Silk Plus', vendor: 'Bambu Lab', color: '#123456' } };
  j = await H['bulk:run']({}, { op: 'filament', ids: ['p1', 'p3', 'p0'], params: { heads, force: false } });
  j = await waitJob(j.id);
  console.log(fmt(j));
  const cmds = printers[1].log.filter((l) => l.startsWith('SET_PRINT_FILAMENT_CONFIG'));
  console.log('   ' + cmds.join('\n   '));
  check(cmds.length === 2 && printers[1].ptc.filament_type[0] === 'PETG' && printers[1].ptc.filament_color_rgba[0] === 'FF7A18FF', 'U1-02 T0 → Polymaker PETG laranja');
  check(printers[3].ptc.filament_vendor[2] === 'Bambu_Lab' && printers[3].ptc.filament_sub_type[2] === 'Silk_Plus', 'espaços viram _ (Klipper não aceita espaço)');
  check(j.items.p0.status === 'skipped', 'impressora imprimindo não é alterada');

  console.log('\n[5] Imprimir arquivo que já está nas impressoras');
  const list = await H['bulk:filesOn']({}, ['p1', 'p3']);
  check(list.some((f) => f.path === 'suporte_rolo.gcode' && f.ids.length === 2), 'lista arquivos comuns às impressoras');
  // recarrega filamento na U1-02 para casar: (metadados do mock dizem PLA, 1 tipo → checa só T0)
  j = await H['bulk:run']({}, { op: 'print', ids: ['p1', 'p3'], params: { filename: 'suporte_rolo.gcode', stagger: 0, checkFilament: true } });
  j = await waitJob(j.id);
  console.log(fmt(j));
  check(j.items.p1.status === 'error' && /PETG/.test(j.items.p1.msg), 'U1-02 recusada (T0 agora é PETG, arquivo pede PLA)');
  check(j.items.p3.status === 'error', 'U1-04 recusada (T0 PETG)');
  j = await H['bulk:run']({}, { op: 'print', ids: ['p1'], params: { filename: 'suporte_rolo.gcode', stagger: 0, checkFilament: false } });
  j = await waitJob(j.id);
  check(j.items.p1.status === 'ok', 'sem checagem: inicia');

  console.log('\n[6] Pausar / retomar / cancelar em massa');
  await sleep(2200);
  j = await waitJob((await H['bulk:run']({}, { op: 'pause', ids })).id);
  console.log(fmt(j));
  check(['p0', 'p1', 'p2', 'p4'].every((id) => j.items[id].status === 'ok'), '4 imprimindo pausadas');
  await sleep(2200);
  j = await waitJob((await H['bulk:run']({}, { op: 'cancel', ids: ['p0', 'p1'] })).id);
  check(printers[0].state === 'cancelled' && printers[1].state === 'cancelled', 'canceladas');

  console.log('\n[7] Só enviar (sem imprimir) para impressora ocupada');
  j = await waitJob((await H['bulk:run']({}, { op: 'send', ids: ['p2'], params: { files, start: false } })).id);
  check(j.items.p2.status === 'ok', 'envio sem impressão funciona mesmo com impressora pausada');

  console.log(fails ? `\n${fails} FALHA(S)` : '\nTODOS OS TESTES PASSARAM');
  process.exit(fails ? 1 : 0);
}

// ---------- UI bridge ----------
function ui() {
  const clients = [];
  E.hub.on('send', (ch, d) => { for (const c of clients) c.write(`data: ${JSON.stringify({ ch, d })}\n\n`); });
  const shim = `window.farm = (() => {
    const call = (ch, ...args) => fetch('/ipc/' + ch, { method: 'POST', body: JSON.stringify(args) }).then(async (r) => { const j = await r.json(); if (!r.ok) throw new Error(j.error); return j.v; });
    const subs = {}; const es = new EventSource('/events');
    es.onmessage = (e) => { const { ch, d } = JSON.parse(e.data); (subs[ch] || []).forEach((f) => f(d)); };
    const on = (ch, f) => (subs[ch] = subs[ch] || []).push(f);
    return { onStates: (cb) => on('states', cb), getConfig: () => call('config:get'), setConfig: (c) => call('config:set', c),
      getAutostart: () => call('autostart:get'), setAutostart: (o) => call('autostart:set', o),
      action: (id, action, value) => call('printer:action', { id, action, value }), sendTrayImages: () => {}, wakeCamera: () => Promise.resolve({ ok: false }),
      openExternal: () => {}, bulkRun: (op, ids, params) => call('bulk:run', { op, ids, params }), bulkEligibility: (op, ids) => call('bulk:eligibility', { op, ids }),
      bulkPickFiles: () => call('bulk:pickFiles'), bulkFilesOn: (ids) => call('bulk:filesOn', ids), bulkJobs: () => call('bulk:jobs'),
      bulkStop: (id) => call('bulk:stop', id), bulkClear: () => call('bulk:clear'), onJob: (cb) => on('bulk:job', cb) };
  })();`;
  http.createServer(async (req, res) => {
    if (req.url === '/events') { res.writeHead(200, { 'Content-Type': 'text/event-stream' }); clients.push(res); return; }
    if (req.url.startsWith('/ipc/')) {
      let b = ''; req.on('data', (c) => (b += c));
      req.on('end', async () => {
        const ch = req.url.slice(5);
        try { const v = await H[ch]({}, ...JSON.parse(b || '[]')); res.writeHead(200); res.end(JSON.stringify({ v: v ?? null })); }
        catch (e) { res.writeHead(500); res.end(JSON.stringify({ error: String(e.message || e) })); }
      });
      return;
    }
    if (req.url === '/shim.js') { res.writeHead(200, { 'Content-Type': 'text/javascript' }); return res.end(shim); }
    let f = req.url.split('?')[0];
    if (f === '/') f = '/renderer/index.html';
    const fp = path.join(REPO, f);
    if (!fp.startsWith(REPO) || !fs.existsSync(fp)) { res.writeHead(404); return res.end(); }
    let data = fs.readFileSync(fp);
    if (f.endsWith('index.html')) data = Buffer.from(data.toString().replace('<script src="i18n.js"></script>', '<script src="/shim.js"></script><script src="i18n.js"></script>').replace(/<meta http-equiv="Content-Security-Policy"[^>]*>/, ''));
    const ct = f.endsWith('.html') ? 'text/html' : f.endsWith('.js') ? 'text/javascript' : f.endsWith('.css') ? 'text/css' : f.endsWith('.png') ? 'image/png' : 'application/octet-stream';
    res.writeHead(200, { 'Content-Type': ct + (ct.startsWith('text') ? '; charset=utf-8' : '') }); res.end(data);
  }).listen(18080, '127.0.0.1', () => console.log('UI on http://127.0.0.1:18080'));
}

if (mode === 'api') api().catch((e) => { console.error(e); process.exit(1); });
else ui();
